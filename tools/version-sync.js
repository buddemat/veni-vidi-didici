#!/usr/bin/env node
// Copies the app version from package.json (single source) to
//   - android/app/build.gradle (versionName + versionCode) and
//   - www/js/version.js (shown in the app, at the bottom of the settings).
// Usage: npm run version:sync (also runs automatically as part of npm run apk).
//
// versionCode is derived from the version (major*10000 + minor*100 + patch,
// e.g. 0.9.1 -> 901, 1.0.0 -> 10000), so it increases with every higher
// version - Android rejects an update with a lower code. Minor and patch
// must therefore stay below 100.

const fs = require('fs');
const path = require('path');

const WURZEL = path.join(__dirname, '..');

function versionCodeAus(version) {
  const teile = version.split('.').map(Number);
  if (teile.length !== 3 || teile.some(t => !Number.isInteger(t) || t < 0) || teile[1] > 99 || teile[2] > 99) {
    throw new Error(`Version "${version}" must have the form X.Y.Z (Y, Z each 0-99).`);
  }
  return teile[0] * 10000 + teile[1] * 100 + teile[2];
}

function main() {
  const { version } = JSON.parse(fs.readFileSync(path.join(WURZEL, 'package.json'), 'utf8'));
  const versionCode = versionCodeAus(version);

  const gradlePfad = path.join(WURZEL, 'android', 'app', 'build.gradle');
  const gradle = fs.readFileSync(gradlePfad, 'utf8');
  const neuesGradle = gradle
    .replace(/versionCode \d+/, `versionCode ${versionCode}`)
    .replace(/versionName "[^"]*"/, `versionName "${version}"`);
  if (!/versionCode \d+/.test(gradle) || !/versionName "[^"]*"/.test(gradle)) {
    throw new Error('versionCode/versionName not found in android/app/build.gradle.');
  }
  fs.writeFileSync(gradlePfad, neuesGradle);

  fs.writeFileSync(
    path.join(WURZEL, 'www', 'js', 'version.js'),
    '// Generated by tools/version-sync.js from package.json - do not edit by hand.\n'
      + `export const APP_VERSION = '${version}';\n`,
  );

  console.log(`Synced version ${version} (versionCode ${versionCode}).`);
}

if (require.main === module) main();
module.exports = { versionCodeAus };
